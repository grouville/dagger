"""Bounded full-module correctness smoke; NOT a performance comparison.

The caller owns the isolated daemon, CLI process records, telemetry and cleanup.
Only this invocation's newly created projects are modified.
"""
import hashlib
import json
from pathlib import Path
import re
import stat
import tomllib

MODULE_SHAS = {
    'contextual': '7e0d30cd3c058907fb858f22925a48fcec591d52860d021d04785a5d692a97d7',
    'before': 'f995374afcfda19442427e1160a12569064a340d2c1cbc5b4cd4a650460ed45a',
    'after': '4d7a0548ade2912f5322cf8bbf62302dbea904dd765a623ca7381bdbfde6b2e7',
}
FILES = {
    'Cargo.toml': '[workspace]\nmembers = ["app", "greeting"]\nresolver = "3"\n',
    'app/Cargo.toml': '[package]\nname = "rust-smoke-app"\nversion = "0.1.0"\nedition = "2024"\n\n[dependencies]\ngreeting = { path = "../greeting" }\n',
    'app/src/main.rs': 'fn main() {\n    println!("{}", greeting::message());\n}\n',
    'greeting/Cargo.toml': '[package]\nname = "greeting"\nversion = "0.1.0"\nedition = "2024"\n',
    'greeting/src/lib.rs': 'pub fn message() -> &\'static str {\n    "hello smoke"\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn greeting_matches() {\n        assert_eq!(super::message(), "hello smoke");\n    }\n}\n',
    'target/unrelated.txt': 'user-owned target data must survive generation\n',
}
LOCK = '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "greeting"\nversion = "0.1.0"\n\n[[package]]\nname = "rust-smoke-app"\nversion = "0.1.0"\ndependencies = [\n "greeting",\n]\n'


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def snapshot(root, generated=False):
    result = {}
    for path in sorted(root.rglob('*')):
        rel = path.relative_to(root)
        if '.git' in rel.parts or str(rel) == 'dagger.lock':
            continue
        managed = rel.parts[:2] == ('target', 'dagger')
        if managed != generated:
            continue
        mode = path.lstat().st_mode
        assert not stat.S_ISLNK(mode), str(rel)
        result[str(rel)] = {'mode': stat.S_IMODE(mode),
                            'kind': 'directory' if path.is_dir() else 'file'}
        if path.is_file():
            result[str(rel)]['sha256'] = sha(path)
    return result


def run_workload(ctx):
    if not __debug__:
        raise RuntimeError('assertions disabled')
    work, assets, out = (Path(ctx[k]) for k in ('work', 'assets', 'out'))
    assert work == Path('/bench/work') and out == work/'results'
    MODULE_SHA = MODULE_SHAS[ctx['module_variant']]
    assert sha(assets/'rust/main.dang') == MODULE_SHA == ctx['module_sha256']
    assert ctx['image_ref'] == 'rust@sha256:39f68a3e8e3ff425f8945ffa91128e60ff930d53e17fbb5214e95824bdd46f1b'
    assert not any(k in ctx['env'] for k in (
        'DAGGER_ENGINE', 'DAGGER_SESSION_PORT', 'DAGGER_SESSION_TOKEN',
        'DAGGER_LEAVE_OLD_ENGINE', '_EXPERIMENTAL_DAGGER_RUNNER_HOST'))
    assert re.fullmatch(r'dagger-isolated-default-flow\.[a-z0-9]+', ctx['owner'])
    projects = work/'project'
    projects.mkdir(exist_ok=False)
    checks = []
    record = dict(status='preparing', performance_comparison=False,
                  module_sha256=MODULE_SHA, ordinary_standalone_cli=True,
                  shared_listener=False, checks=checks,
                  source_fixture='new two-member Rust workspace; local library dependency and one test',
                  scope='runtime smoke only; no real-repo speedup or full-platform coverage claim',
                  artifact_revisit_gates=[])
    ctx['record']['module_smoke'] = record

    def checkpoint():
        (out/'module-smoke.json').write_text(json.dumps(record, indent=2)+'\n')
        ctx['save']()

    def create(name, locked):
        root = projects/name
        root.mkdir(exist_ok=False)
        for relative, content in FILES.items():
            path = root/relative
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open('x') as stream:
                stream.write(content)
        (root/'target').chmod(0o750)
        (root/'target/unrelated.txt').chmod(0o640)
        with (root/'rust-toolchain.toml').open('xb') as stream:
            stream.write((assets/'rust-toolchain.toml').read_bytes())
        if locked:
            with (root/'Cargo.lock').open('x') as stream:
                stream.write(LOCK)
        config = ('[modules.rust]\nsource = '+json.dumps(str(assets/'rust'))+
                  '\n[modules.rust.settings]\nlocked = '+str(locked).lower()+
                  '\ncacheKey = '+json.dumps(ctx['owner']+'-'+name)+'\n')
        with (root/'dagger.toml').open('x') as stream:
            stream.write(config)
        ctx['run']('init-'+name, ['git', 'init', '-q'], cwd=root)
        return root

    def invoke(label, root, args, expected=0):
        result = ctx['run'](label, [ctx['cli'], '--profile']+args,
                            cwd=root, expected=expected, timeout=600)
        checks.append(dict(label=label, argv=args, exit_code=result['exit_code'],
                           milliseconds=result['milliseconds'], profiled=True))
        checkpoint()
        return result

    def run_binary(label, root, expected):
        executable = root/'target/dagger/debug/rust-smoke-app'
        assert executable.is_file() and not executable.is_symlink()
        assert executable.stat().st_mode & 0o111
        # Validate the Linux/GNU artifact in its matching Rust runtime, not the
        # Alpine controller. This is not timed as a native Cargo comparison.
        args = ctx['docker']+['run', '--pull=never', '--name', 'artifact-'+label,
               '--label', 'dagger.rust-bench.owner='+ctx['owner'],
               '--mount', 'type=bind,src='+str(root)+',dst=/src,readonly',
               ctx['native_image_id'], '/src/target/dagger/debug/rust-smoke-app']
        result = ctx['run']('artifact-'+label, args)
        assert result['stdout'].strip() == expected, result['stdout']

    root = create('locked', True)
    original = snapshot(root)
    record['initial_source'] = original
    checkpoint()
    try:
        # Retain the existing failed-first-command discovery label. No API
        # introspection, image query or listener precedes this ordinary check.
        invoke('warmup-dagger', root, ['check', 'rust:check'])
        ctx['after_first']()
        for name in ('fmt', 'clippy', 'test'):
            invoke(name, root, ['check', 'rust:'+name])
        assert snapshot(root) == original, 'checks modified project files'
        invoke('generate', root, ['generate', '-y'])
        assert snapshot(root) == original, 'locked generation modified unrelated files/modes'
        generated = snapshot(root, generated=True)
        record['initial_generated'] = generated
        assert generated and (root/'target/dagger/debug/libgreeting.rlib').is_file()
        run_binary('initial', root, 'hello smoke')
        invoke('generate-unchanged', root, ['generate', '-y'])
        assert snapshot(root) == original and snapshot(root, generated=True) == generated
        invoke('check-default-selection', root, ['check'])
        assert snapshot(root) == original and snapshot(root, generated=True) == generated

        library = root/'greeting/src/lib.rs'
        library.write_text(FILES['greeting/src/lib.rs'].replace('hello smoke', 'hello edited'))
        edited = snapshot(root)
        invoke('library-edit-check', root, ['check', 'rust:check'])
        invoke('library-edit-generate', root, ['generate', '-y'])
        assert snapshot(root) == edited
        assert snapshot(root, generated=True) != generated
        run_binary('edited', root, 'hello edited')

        app = root/'app/src/main.rs'
        app.write_text(FILES['app/src/main.rs'].replace('greeting::message()', 'greeting::does_not_exist()'))
        # This single check propagates Cargo's compiler failure exit status.
        # Require that exact failure, then verify the compiler diagnostic.
        failure = invoke('failure', root, ['check', 'rust:check'], expected=101)
        assert 'does_not_exist' in failure['stderr']+failure['stdout']
        app.write_text(FILES['app/src/main.rs'])
        invoke('repair', root, ['check', 'rust:check'])
        library.write_text(FILES['greeting/src/lib.rs'])
        invoke('revisit-generate', root, ['generate', '-y'])
        assert snapshot(root) == original
        run_binary('revisited', root, 'hello smoke')
        # Preserve this gate even if GC forced a fresh, byte-different rebuild.
        # Continue recording the remaining flow; the analyzer still rejects a
        # failed revisit gate. Binary behavior is independently checked above.
        revisited = snapshot(root, generated=True)
        record['artifact_revisit_gates'].append(dict(label='revisit-generate',
            byte_identical=revisited == generated, artifacts=revisited))

        unlocked = create('unlocked', False)
        before_unlocked = snapshot(unlocked)
        assert not (unlocked/'Cargo.lock').exists()
        invoke('unlocked-generate', unlocked, ['generate', '-y'])
        lock = unlocked/'Cargo.lock'
        assert lock.is_file() and not lock.is_symlink()
        parsed = tomllib.loads(lock.read_text())
        assert {p['name'] for p in parsed['package']} == {'greeting', 'rust-smoke-app'}
        after_unlocked = snapshot(unlocked)
        assert {k:v for k,v in after_unlocked.items() if k != 'Cargo.lock'} == before_unlocked
        unlocked_artifacts = snapshot(unlocked, generated=True)
        invoke('unlocked-generate-unchanged', unlocked, ['generate', '-y'])
        assert snapshot(unlocked) == after_unlocked
        assert snapshot(unlocked, generated=True) == unlocked_artifacts
        run_binary('unlocked', unlocked, 'hello smoke')

        # Fixed tail/invalidation pilot on the actual default check selection.
        # Each edit changes both observable behavior and its unit-test assertion.
        # This is not a native comparison; keep all profiled process timings.
        for sample in range(6):
            before_loop = snapshot(root)
            before_artifacts = snapshot(root, generated=True)
            invoke(f'loop-{sample}-cached-check', root, ['check'])
            assert snapshot(root) == before_loop and snapshot(root, generated=True) == before_artifacts
            message = f'hello loop {sample}'
            library.write_text(FILES['greeting/src/lib.rs'].replace('hello smoke', message))
            loop_source = snapshot(root)
            # Ordinary check also checks generators: stale host artifacts are
            # correctly reported as drift, even though Rust checks pass.
            drift = invoke(f'loop-{sample}-edit-check', root, ['check'], expected=1)
            assert "produced changes; run 'dagger generate rust:build' to apply" in drift['stderr']+drift['stdout']
            assert snapshot(root) == loop_source, 'checks changed edited source or target metadata'
            assert snapshot(root, generated=True) == before_artifacts, 'checks unexpectedly applied generated artifacts'
            invoke(f'loop-{sample}-generate', root, ['generate', '-y'])
            assert snapshot(root) == loop_source
            assert snapshot(root, generated=True) != before_artifacts
            run_binary(f'loop-{sample}', root, message)
        library.write_text(FILES['greeting/src/lib.rs'])
        invoke('loop-restore-generate', root, ['generate', '-y'])
        assert snapshot(root) == original
        run_binary('loop-restored', root, 'hello smoke')
        restored = snapshot(root, generated=True)
        record['artifact_revisit_gates'].append(dict(label='loop-restore-generate',
            byte_identical=restored == generated, artifacts=restored))
        record['tail_pilot'] = dict(iterations=6, unchanged_default_checks=6,
            novel_library_edits=6, ordinary_default_checks=True, exported_artifacts_verified=True,
            profiled=True, native_comparison=False,
            generate_scope='follow-up cached-build artifact export after default check; not independent edit-to-generate')

        # These are correctness probes, not representative timing scenarios.
        # Inputs excluded from a source digest (module settings / generated
        # outputs) must still affect the correct outer function or generator.
        probes = []
        record['input_boundary_probes'] = probes
        binary = root/'target/dagger/debug/rust-smoke-app'
        binary.write_bytes(binary.read_bytes()+b'\nowned-fixture-artifact-tamper\n')
        tampered = snapshot(root, generated=True)
        drift = invoke('target-only-drift', root, ['check'], expected=1)
        assert "produced changes; run 'dagger generate rust:build' to apply" in drift['stderr']+drift['stdout']
        assert snapshot(root) == original and snapshot(root, generated=True) == tampered
        invoke('target-only-repair', root, ['generate', '-y'])
        assert snapshot(root, generated=True) == generated
        run_binary('target-only-repaired', root, 'hello smoke')
        probes.append(dict(name='target-only-drift', passed=True))

        manifest = root/'app/Cargo.toml'
        manifest.write_text(FILES['app/Cargo.toml'].replace('edition = "2024"', 'edition = "2099"'))
        failed_manifest = invoke('manifest-invalid', root, ['check', 'rust:check'], expected=101)
        assert '2099' in failed_manifest['stderr']+failed_manifest['stdout']
        manifest.write_text(FILES['app/Cargo.toml'])
        invoke('manifest-repair', root, ['check', 'rust:check'])
        probes.append(dict(name='manifest-invalid', passed=True))

        cargo_config_dir = root/'.cargo'
        assert not cargo_config_dir.exists()
        cargo_config_dir.mkdir()
        cargo_config = cargo_config_dir/'config.toml'
        cargo_config.write_text('[build\n')
        failed_config = invoke('cargo-config-invalid', root, ['check', 'rust:check'], expected=101)
        assert 'config.toml' in failed_config['stderr']+failed_config['stdout']
        cargo_config.unlink()
        cargo_config_dir.rmdir()
        invoke('cargo-config-repair', root, ['check', 'rust:check'])
        probes.append(dict(name='cargo-config-invalid', passed=True))

        toolchain_file = root/'rust-toolchain.toml'
        toolchain_bytes = toolchain_file.read_bytes()
        toolchain_file.write_text('[toolchain]\nchannel = ""\n')
        failed_toolchain = invoke('toolchain-invalid', root, ['check', 'rust:check'], expected=1)
        assert 'toolchain' in failed_toolchain['stderr']+failed_toolchain['stdout']
        toolchain_file.write_bytes(toolchain_bytes)
        invoke('toolchain-repair', root, ['check', 'rust:check'])
        probes.append(dict(name='toolchain-invalid', passed=True))

        module_config = root/'dagger.toml'
        module_config_text = module_config.read_text()
        module_config.write_text(module_config_text+'features = ["missing_feature_for_cache_test"]\n')
        failed_settings = invoke('module-settings-invalid', root, ['check', 'rust:check'], expected=101)
        assert 'missing_feature_for_cache_test' in failed_settings['stderr']+failed_settings['stdout']
        module_config.write_text(module_config_text)
        invoke('module-settings-repair', root, ['check', 'rust:check'])
        probes.append(dict(name='module-settings-invalid', passed=True))
        assert snapshot(root) == original and snapshot(root, generated=True) == generated

        # Independent user edit -> generate, with no check warming that build.
        # Keep follow-up export measurements separate from this miss path.
        for sample in range(6):
            before_direct = snapshot(root, generated=True)
            message = f'hello direct {sample}'
            library.write_text(FILES['greeting/src/lib.rs'].replace('hello smoke', message))
            direct_source = snapshot(root)
            invoke(f'direct-{sample}-edit-generate', root, ['generate', '-y'])
            assert snapshot(root) == direct_source
            direct_generated = snapshot(root, generated=True)
            assert direct_generated != before_direct
            run_binary(f'direct-{sample}', root, message)
            invoke(f'direct-{sample}-cached-generate', root, ['generate', '-y'])
            assert snapshot(root) == direct_source
            assert snapshot(root, generated=True) == direct_generated
        library.write_text(FILES['greeting/src/lib.rs'])
        invoke('direct-restore-generate', root, ['generate', '-y'])
        assert snapshot(root) == original and snapshot(root, generated=True) == generated
        record['direct_generate_pilot'] = dict(iterations=6, no_preceding_check=True,
            ordinary_standalone_cli=True, bytes_modes_and_binary_behavior_verified=True)

        # The self-call must inherit settings from the exact receiving object.
        module_config.write_text(module_config_text+'features = ["missing_feature_for_cache_test"]\n')
        failed_build_settings = invoke('module-settings-build-invalid', root,
                                       ['generate', '-y'], expected=101)
        assert 'missing_feature_for_cache_test' in failed_build_settings['stderr']+failed_build_settings['stdout']
        assert snapshot(root, generated=True) == generated
        module_config.write_text(module_config_text)
        invoke('module-settings-build-repair', root, ['generate', '-y'])
        assert snapshot(root) == original and snapshot(root, generated=True) == generated

        # Public module self types must remain valid under an installation alias.
        aliased = create('alias', True)
        alias_config = aliased/'dagger.toml'
        alias_config.write_text(alias_config.read_text().replace('[modules.rust', '[modules.ferris'))
        alias_source = snapshot(aliased)
        invoke('aliased-generate', aliased, ['generate', '-y'])
        assert snapshot(aliased) == alias_source
        run_binary('aliased', aliased, 'hello smoke')
        record['generator_boundary_probes'] = dict(settings_inherited=True, installed_alias_passed=True)


        # Output inventory and metadata are inputs, not assumed durable state.
        output_probes = []
        record['output_state_probes'] = output_probes

        def assert_drift_and_repair(name):
            before_probe = snapshot(root, generated=True)
            drift = invoke(name+'-drift', root, ['check'], expected=1)
            assert "produced changes; run 'dagger generate rust:build' to apply" in drift['stderr']+drift['stdout']
            assert snapshot(root, generated=True) == before_probe
            invoke(name+'-repair', root, ['generate', '-y'])
            assert snapshot(root) == original
            assert snapshot(root, generated=True) == generated
            output_probes.append(name)

        binary = root/'target/dagger/debug/rust-smoke-app'
        binary.unlink()
        assert_drift_and_repair('artifact-deleted')
        obsolete = root/'target/dagger/obsolete-artifact'
        obsolete.write_text('owned fixture stale output')
        assert_drift_and_repair('artifact-obsolete')
        binary.chmod(0o600)
        assert_drift_and_repair('artifact-mode')

        managed = root/'target/dagger'
        managed.rename(work/'saved-managed-absent')
        assert_drift_and_repair('managed-absent')
        managed.rename(work/'saved-managed-empty')
        managed.mkdir(mode=0o755)
        assert_drift_and_repair('managed-empty')

        # Stabilize the observed output state before testing a filtered sibling.
        invoke('output-state-stabilize', root, ['check'])
        invoke('output-state-repeat', root, ['check'])
        unrelated = root/'target/unrelated.txt'
        unrelated.write_text('changed user-owned sibling')
        unrelated_source = snapshot(root)
        invoke('unrelated-target-check', root, ['check'])
        assert snapshot(root) == unrelated_source and snapshot(root, generated=True) == generated
        unrelated.write_text(FILES['target/unrelated.txt'])
        assert snapshot(root) == original
        output_probes.append('unrelated-target')

        outside = work/'outside-sentinel'
        outside.mkdir(exist_ok=False)
        sentinel = outside/'sentinel.txt'
        sentinel.write_text('outside must remain untouched')
        sentinel_mode = stat.S_IMODE(sentinel.stat().st_mode)
        for name, path in (('managed-symlink', managed), ('target-symlink', root/'target')):
            saved = work/('saved-'+name)
            path.rename(saved)
            try:
                path.symlink_to(outside, target_is_directory=True)
                invoke(name, root, ['generate', '-y'], expected=1)
                assert path.is_symlink()
                assert list(outside.iterdir()) == [sentinel]
                assert sentinel.read_text() == 'outside must remain untouched'
                assert stat.S_IMODE(sentinel.stat().st_mode) == sentinel_mode
            finally:
                if path.is_symlink():
                    path.unlink()
                saved.rename(path)
            assert snapshot(root) == original and snapshot(root, generated=True) == generated
            output_probes.append(name)

        unlocked_lock = unlocked/'Cargo.lock'
        saved_lock = work/'saved-unlocked-lock'
        unlocked_lock.rename(saved_lock)
        try:
            unlocked_lock.symlink_to(sentinel)
            invoke('unlocked-lock-symlink', unlocked, ['generate', '-y'], expected=1)
            assert unlocked_lock.is_symlink()
            assert sentinel.read_text() == 'outside must remain untouched'
        finally:
            if unlocked_lock.is_symlink():
                unlocked_lock.unlink()
            saved_lock.rename(unlocked_lock)
        assert snapshot(unlocked) == after_unlocked
        assert snapshot(unlocked, generated=True) == unlocked_artifacts
        output_probes.append('unlocked-lock-symlink')
        ctx['dump']('module-smoke.wcprof', cache=True)
        record['status'] = 'runtime-assertions-passed-profile-analysis-pending'
    except BaseException as error:
        record.update(status='failed', error=repr(error))
        raise
    finally:
        try:
            actual = snapshot(root)
            record['final_source'] = actual
            record['source_differences'] = {
                name: {'before': original.get(name), 'after': actual.get(name)}
                for name in sorted(set(original) | set(actual))
                if original.get(name) != actual.get(name)
            }
            record['final_generated'] = snapshot(root, generated=True)
        except Exception as error:
            record['final_snapshot_error'] = repr(error)
        checkpoint()
